        /// <summary>
        /// Descriptors for the smoke suites, in the same deterministic order as <see cref="ArmadaTestSuites.All"/>.
        /// </summary>
        public static IReadOnlyList<TestSuiteDescriptor> All
        {
            get { return _Build(); }
        }

        #endregion

        #region Private-Methods

        private static IReadOnlyList<TestSuiteDescriptor> _Build()
        {
            HashSet<string> wanted = new HashSet<string>(SuiteIds, StringComparer.Ordinal);
            IReadOnlyList<TestSuiteDescriptor> all = ArmadaTestSuites.All;

            // ARMADA_TEST_SUITES narrows ArmadaTestSuites.All; only check for missing suites on an unfiltered run.
            if (String.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("ARMADA_TEST_SUITES")))
            {
                HashSet<string> known = new HashSet<string>(all.Select(d => d.SuiteId), StringComparer.Ordinal);
                List<string> missing = SuiteIds.Where(id => !known.Contains(id)).ToList();
                if (missing.Count > 0)
                {
                    throw new InvalidOperationException(
                        "Smoke suites not found in Test.Shared (renamed or removed?): " + String.Join(", ", missing));
                }
            }

            return all.Where(d => wanted.Contains(d.SuiteId)).ToList();
        }

        #endregion
    }
